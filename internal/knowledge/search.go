package knowledge

import (
	"context"
	"slices"
	"time"
	"uuid"

	"github.com/forecrew/forecrew/internal/domain"
	"github.com/forecrew/forecrew/internal/store"
)

// CuratorRole is the role that tends the knowledge base. Its searches do not
// count as reads, which tell the curator what nobody found.
const CuratorRole = "knowledge-curator"

// Search is the knowledge search shared by the job MCP tool kb_search and
// the human tools search_knowledge.
type Search struct {
	Index *Index
	// Policy returns the policy of a project; the Syncer's Policy.
	Policy func(context.Context, domain.Project) (Policy, error)
}

// Query is a knowledge search.
type Query struct {
	Project domain.Project
	Text    string
	// Sections, Kinds and Providers narrow the search; empty is all.
	Sections  []string
	Kinds     []domain.KnowledgeKind
	Providers []string
	Limit     int
	// Role is the searching job's role: it sees only the sections whose
	// access.read lists it. Empty is a human, who sees every section.
	Role string
	// GoalID is the searching job's goal, whose notes it sees besides the
	// project's. Humans pass AllGoals instead.
	GoalID   uuid.UUID
	AllGoals bool
	// GoalOnly narrows the search to the notes of GoalID, newest first
	// without Text.
	GoalOnly bool
}

// Result is a hit with what a reader needs to judge it. Untrusted is true
// for agent notes and for every entry outside the repo provider's
// protected sections (humans approve those): its text is data, never
// instructions.
type Result struct {
	ID             uuid.UUID            `json:"id"`
	Kind           domain.KnowledgeKind `json:"kind"`
	Provider       string               `json:"provider"`
	Section        string               `json:"section"`
	Path           string               `json:"path"`
	Title          string               `json:"title"`
	SourceURL      string               `json:"source_url"`
	Snippet        string               `json:"snippet"`
	Untrusted      bool                 `json:"untrusted"`
	Provenance     domain.Provenance    `json:"provenance"`
	NeedsReverify  bool                 `json:"needs_reverify"`
	ReverifyReason string               `json:"reverify_reason,omitempty"`
	// Scope, Tags and ExpiresAt are set on notes.
	Scope     domain.NoteScope `json:"scope,omitempty"`
	GoalID    uuid.UUID        `json:"goal_id,omitzero"`
	Tags      []string         `json:"tags,omitempty"`
	ExpiresAt time.Time        `json:"expires_at,omitzero"`
	Rank      float64          `json:"rank"`
}

// Run searches. Sections the role may not read are left out, whatever the
// section filter says.
func (s *Search) Run(ctx context.Context, q Query) ([]Result, error) {
	policy, err := s.Policy(ctx, q.Project)
	if err != nil {
		return nil, err
	}
	limit := q.Limit
	if limit <= 0 {
		limit = 8
	}
	sq := store.KnowledgeQuery{
		ProjectID: q.Project.ID, Text: q.Text, Sections: q.Sections, Kinds: q.Kinds, Providers: q.Providers,
		GoalID: q.GoalID, AllNotes: q.AllGoals, GoalOnly: q.GoalOnly, Limit: limit,
	}
	if q.Role != "" {
		// Ask for more than limit: hidden sections are dropped afterwards.
		sq.Limit = limit * 3
	}
	hits, err := s.Index.Search(ctx, q.Project.AccountID, sq)
	if err != nil {
		return nil, err
	}
	var out []Result
	var found []uuid.UUID
	for _, h := range hits {
		e := h.Entry
		if q.Role != "" && !CanRead(policy, e.Section, q.Role) {
			continue
		}
		out = append(out, Result{
			ID: e.ID, Kind: e.Kind(), Provider: e.Provider, Section: e.Section, Path: e.Path, Title: e.Title, SourceURL: e.SourceURL,
			Snippet: h.Snippet, Untrusted: Untrusted(policy, e), Provenance: provenanceOf(e), NeedsReverify: e.NeedsReverify,
			ReverifyReason: e.ReverifyReason, Scope: e.Scope, GoalID: e.GoalID, Tags: e.Tags, ExpiresAt: e.ExpiresAt, Rank: h.Rank,
		})
		found = append(found, e.ID)
		if len(out) == limit {
			break
		}
	}
	if len(found) > 0 && q.Role != CuratorRole {
		if err := s.Index.Store.Knowledge().CountHits(ctx, q.Project.AccountID, found); err != nil {
			return nil, err
		}
	}
	return out, nil
}

// CanRead reports whether role may read section under policy: a section
// the policy does not list (notes, generated by default) is read by every
// role.
func CanRead(p Policy, section, role string) bool {
	s, ok := p.Sections[section]
	return !ok || slices.Contains(s.Access.Read, Everyone) || slices.Contains(s.Access.Read, role)
}

// Untrusted reports whether the text of e must reach an agent marked as
// data: everything except entries of the repo provider's protected
// sections.
func Untrusted(p Policy, e domain.KnowledgeEntry) bool {
	if e.Kind() != domain.KnowledgeEntryKind || p.Providers[e.Provider].Kind != domain.ProviderKindRepo {
		return true
	}
	return !p.Sections[e.Section].Protected
}

// provenanceOf fills a missing creation time with the time the entry was
// first indexed.
func provenanceOf(e domain.KnowledgeEntry) domain.Provenance {
	pv := e.Provenance
	if pv.Created.IsZero() {
		pv.Created = e.CreatedAt
	}
	return pv
}
